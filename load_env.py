import gzip
import os
import re
Import("env")


def generate_gzip_web_ui(src_path, dst_path):
    if not os.path.isfile(src_path):
        return
    with open(src_path, "r", encoding="utf-8") as f:
        text = f.read()
    match = re.search(r'R"rawliteral\((.*?)\)rawliteral"', text, re.S)
    if not match:
        return
    html_bytes = match.group(1).encode("utf-8")
    gz_bytes = gzip.compress(html_bytes, compresslevel=9, mtime=0)

    lines = [
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
        f"// Auto-generated by load_env.py from include/web_ui.h ({len(html_bytes)} -> {len(gz_bytes)} bytes)",
        f"constexpr size_t WEB_UI_HTML_GZ_LEN = {len(gz_bytes)};",
        "const uint8_t WEB_UI_HTML_GZ[] PROGMEM = {",
    ]
    for i in range(0, len(gz_bytes), 16):
        chunk = gz_bytes[i : i + 16]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    content = "\n".join(lines) + "\n"

    if os.path.isfile(dst_path):
        with open(dst_path, "r", encoding="utf-8") as f:
            if f.read() == content:
                return
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[web_ui] Compressed HTML: {len(html_bytes)} -> {len(gz_bytes)} bytes ({dst_path})")


def read_fw_version(config_path):
    if not os.path.isfile(config_path):
        return None
    with open(config_path, "r", encoding="utf-8") as f:
        match = re.search(r'#define\s+FW_VERSION\s+"([^"]+)"', f.read())
    return match.group(1).strip() if match else None


def parse_env_file(path):
    values = {}
    if not os.path.isfile(path):
        return values
    with open(path, "r", encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            key = key.strip()
            val = val.strip()
            if len(val) >= 2 and ((val[0] == val[-1] == '"') or (val[0] == val[-1] == "'")):
                val = val[1:-1]
            values[key] = val
    return values


project_dir = env.subst("$PROJECT_DIR")

generate_gzip_web_ui(
    os.path.join(project_dir, "include", "web_ui.h"),
    os.path.join(project_dir, "include", "web_ui_gz.h"),
)

fw_version = read_fw_version(os.path.join(project_dir, "include", "config.h"))
if fw_version:
    safe_ver = re.sub(r"[^0-9A-Za-z._-]", "_", fw_version)
    env.Replace(PROGNAME=f"firmware_v{safe_ver}")

env_vars = {}
for candidate in (
    os.path.join(project_dir, ".env"),
    os.path.join(project_dir, "include", ".env"),
):
    env_vars.update(parse_env_file(candidate))

string_keys = {
    "WIFI_SSID": "DEFAULT_WIFI_SSID",
    "WIFI_PASS": "DEFAULT_WIFI_PASS",
    "TIMEZONE": "DEFAULT_TIMEZONE",
    "ADSB_LOL_API_KEY": "ADSB_LOL_API_KEY",
    "OTA_PASSWORD": "OTA_PASSWORD",
}

for src_key, macro_name in string_keys.items():
    if env_vars.get(src_key):
        env.Append(CPPDEFINES=[(macro_name, env.StringifyMacro(env_vars[src_key]))])

for src_key, macro_name in (
    ("LATITUDE", "DEFAULT_LATITUDE"),
    ("LONGITUDE", "DEFAULT_LONGITUDE"),
):
    if env_vars.get(src_key):
        try:
            float(env_vars[src_key])
            env.Append(CPPDEFINES=[(macro_name, env_vars[src_key])])
        except ValueError:
            pass

if env.GetProjectOption("upload_protocol", "") == "espota":
    if env_vars.get("OTA_HOST"):
        env.Replace(UPLOAD_PORT=env_vars["OTA_HOST"])
    if env_vars.get("OTA_PASSWORD"):
        env.Append(UPLOAD_FLAGS=["--auth=" + env_vars["OTA_PASSWORD"]])
